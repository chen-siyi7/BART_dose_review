args<-commandArgs(trailingOnly=TRUE)
stopifnot(length(args)==1L,!file.exists(args[1L]),dir.exists(dirname(args[1L])))
script<-sub('^--file=','',grep('^--file=',commandArgs(),value=TRUE))
root<-normalizePath(file.path(dirname(script),'..'))
out<-args[1L];parent<-normalizePath(dirname(out))
stopifnot(parent!=root,!startsWith(parent,paste0(root,'/')))
for(n in c('decisions.R','sensitivity.R','queries.R','audits.R','query_audit.R'))
  source(file.path(root,'R',n))
verify_manifest(root)
dir.create(out)
save_json(audit_queries(file.path(root,'data'),out),file.path(out,'RESULTS.json'))
