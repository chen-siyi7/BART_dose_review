
args<-commandArgs(trailingOnly=TRUE);stopifnot(length(args)==2L)
worker<-as.integer(args[1]);workers<-as.integer(args[2]);stopifnot(worker>=1L,worker<=workers)
script<-sub('^--file=','',grep('^--file=',commandArgs(),value=TRUE));root<-normalizePath(dirname(script))
source(file.path(root,'analysis_helpers.R'))
planfile<-file.path(root,'PLAN.json');plan<-jsonlite::read_json(planfile,simplifyVector=TRUE)
stopifnot(startsWith(plan$status,'FROZEN'),plan$chains==4L,plan$retained==32000L,
  plan$burnin==8000L,plan$total_quantities==57L)
source_root<-normalizePath(file.path(root,'..','..'))
source_audit<-new.env(parent=baseenv())
sys.source(file.path(source_root,'R/audits.R'),envir=source_audit)
for(f in c('analysis_helpers.R','prepare_inputs.R','fit_worker.R','summarize.R'))
  stopifnot(source_audit$source_hash_matches(file.path(root,f),plan$source_hashes[[f]],source_root))
inputfile<-file.path(root,'inputs/INPUTS.rds');stopifnot(identical(plan$input_sha256,ast_sha(inputfile)))
input<-readRDS(inputfile)
lib<-Sys.getenv('BART_LIBRARY',unset='');if(nzchar(lib)).libPaths(c(normalizePath(lib),.libPaths()))
suppressPackageStartupMessages(library(BART));stopifnot(as.character(packageVersion('BART'))=='2.9.9')
jobs<-expand.grid(role=seq_len(plan$chains),model_id=names(input$models),stringsAsFactors=FALSE)
out<-file.path(root,'chains');dir.create(out,showWarnings=FALSE)
for(i in seq_len(nrow(jobs))[(seq_len(nrow(jobs))-1L)%%workers==worker-1L]) {
  job<-jobs[i,];file<-file.path(out,paste0(job$model_id,'_chain',job$role,'.rds'))
  stopifnot(!file.exists(file))
  cat('Starting',job$model_id,'chain',job$role,'\n');flush.console()
  result<-ast_fit_one(input,plan,job$model_id,job$role)
  result$plan_sha256<-ast_sha(planfile);result$input_sha256<-ast_sha(inputfile)
  tmp<-paste0(file,'.tmp');saveRDS(result,tmp);stopifnot(file.rename(tmp,file))
  cat('Completed',job$model_id,'chain',job$role,'in',round(result$elapsed_seconds,2),'seconds\n');flush.console()
}
cat('Worker',worker,'complete\n')
